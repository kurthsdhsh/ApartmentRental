    private void refreshTable() {
    try {
        fillTable(dao.getAll());
        
    } catch (SQLException ex) {
        ErrorHelper.show(this, ex);
    }
}
    
    private void fillTable(List<Unit> list) {
    DefaultTableModel m = (DefaultTableModel) tblUnits.getModel();
    m.setRowCount(0);
    for (Unit u : list) {
        m.addRow(new Object[]{
            u.getUnitId(),
            u.getUnitNo(),
            u.getUnitType(),
            u.getFloorNo(),
            u.getMonthlyRent(),
            u.getStatus()
        });
    }
    lblInfo.setText(list.isEmpty() ? "No records found." : list.size() + " unit(s)");
}
    
